// Writes the Grand Exchange offline price snapshot: one cache enum of obj -> average price, taken
// from the OSRS Wiki real-time prices API (24h averages, latest trades where an item has none).
//
//   node tools/ge-prices/snapshot.mjs
//
// Run from the repo root, then `gradlew buildCache`.

import { readFileSync, writeFileSync } from "node:fs";

const API = "https://prices.runescape.wiki/api/v1/osrs";
const USER_AGENT = "OpenRune-Server Grand Exchange snapshot (github.com/osrs-solo/OpenRune-Server)";
const GAMEVALS = ".data/gamevals-binary/gamevals.dat";
const OUTPUT =
    "content/other/grand-exchange/pack/src/main/resources/pack/configs/ge_guide_prices.toml";
const MAX_INT = 2147483647;

function readObjNames(path) {
    const data = readFileSync(path);
    let offset = 0;
    const int = () => {
        const value = data.readInt32BE(offset);
        offset += 4;
        return value;
    };
    const string = () => {
        const length = data.readUInt16BE(offset);
        offset += 2;
        const value = data.toString("latin1", offset, offset + length);
        offset += length;
        return value;
    };
    const names = new Map();
    const tables = int();
    for (let t = 0; t < tables; t++) {
        const table = string();
        const entries = int();
        for (let e = 0; e < entries; e++) {
            const entry = string();
            if (table !== "obj") continue;
            const split = entry.lastIndexOf("=");
            names.set(Number(entry.slice(split + 1)), entry.slice(0, split));
        }
        if (table === "obj") break;
    }
    return names;
}

async function fetchJson(endpoint) {
    const response = await fetch(`${API}/${endpoint}`, { headers: { "User-Agent": USER_AGENT } });
    if (!response.ok) throw new Error(`${endpoint}: HTTP ${response.status}`);
    return response.json();
}

function average(...values) {
    const present = values.filter((v) => typeof v === "number" && v > 0);
    if (present.length === 0) return null;
    return Math.round(present.reduce((a, b) => a + b, 0) / present.length);
}

const names = readObjNames(GAMEVALS);
const [mapping, daily, latest] = await Promise.all([
    fetchJson("mapping"),
    fetchJson("24h"),
    fetchJson("latest"),
]);

const lines = [];
let skipped = 0;
for (const item of mapping.sort((a, b) => a.id - b.id)) {
    const name = names.get(item.id);
    if (!name) {
        skipped++;
        continue;
    }
    const day = daily.data[item.id] ?? {};
    const now = latest.data[item.id] ?? {};
    const price = average(day.avgHighPrice, day.avgLowPrice) ?? average(now.high, now.low);
    if (price === null) continue;
    lines.push(`"obj.${name}" = ${Math.min(price, MAX_INT)}`);
}

const stamp = new Date().toISOString().slice(0, 10);
writeFileSync(
    OUTPUT,
    `# Generated by tools/ge-prices/snapshot.mjs on ${stamp} from prices.runescape.wiki.\n` +
        `# Offline fallback for Grand Exchange guide prices; do not edit by hand.\n` +
        `[[enum]]\nisServerOnly = true\nid = "enum.ge_guide_prices"\n` +
        `keyType = "OBJ"\nvalueType = "INT"\n\n[enum.values]\n` +
        lines.join("\n") +
        "\n",
);
console.log(`Wrote ${lines.length} prices to ${OUTPUT} (${skipped} wiki items not in this cache).`);
