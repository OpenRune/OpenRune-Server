package org.rsmod.content.other.travelcoverage

import java.nio.file.Files
import java.nio.file.Path

/** Writes `auto-travel-tags.toml`: staircases, gangplanks and trapdoors for the travel handler. */
object AutoTravelTagWriter {
    fun write(result: AutoTravelResult, dir: Path) {
        Files.createDirectories(dir)
        val toml = buildString {
            appendLine("# Generated by the travel coverage report (gradlew travelReport). The travel handler")
            appendLine("# finds each loc's far end when it is used, so these only need tagging.")
            for (travel in result.travel.sortedBy { it.symbol }) {
                appendLine()
                appendLine("# ${travel.placements} placements")
                append(entry(travel.symbol, travel.kind.content, null))
            }
            for (trapdoor in result.trapdoors.sortedBy { it.closed }) {
                appendLine()
                appendLine("# Trapdoor - ${trapdoor.placements} placements")
                append(entry(trapdoor.closed, "content.auto_trapdoor_closed", trapdoor.opened))
                appendLine()
                append(entry(trapdoor.opened, "content.auto_trapdoor_open", trapdoor.closed))
            }
        }
        Files.writeString(dir.resolve("auto-travel-tags.toml"), toml)
    }

    private fun entry(symbol: String, content: String, nextStage: String?): String =
        buildString {
            appendLine("[[object]]")
            appendLine("id = \"$symbol\"")
            appendLine("inherit = \"$symbol\"")
            appendLine("contentGroup = \"$content\"")
            if (nextStage != null) {
                appendLine()
                appendLine("[object.params]")
                appendLine("\"param.next_loc_stage\" = \"$nextStage\"")
            }
        }
}
