package org.rsmod.content.other.travelcoverage

import dev.openrune.ServerCacheManager
import dev.openrune.rscm.RSCM
import dev.openrune.rscm.RSCM.asRSCM
import dev.openrune.rscm.RSCMType
import dev.openrune.types.ObjectServerType
import dev.openrune.types.SequenceServerType
import java.nio.file.Files
import java.nio.file.Path
import org.rsmod.api.config.refs.params

/**
 * Writes `ladder-tags.toml`, a pack config that gives each paired ladder the content group its
 * shared script answers, and `ladder-skipped.md`, the ladders left for hand-written handlers.
 * The ladder scripts play the loc's `climb_anim`, so a ladder without one borrows the animation
 * most already-working ladders use.
 */
object LadderTagWriter {
    fun write(
        result: LadderPairingResult,
        dir: Path,
        type: (Int) -> ObjectServerType?,
        internalName: (Int) -> String,
    ) {
        Files.createDirectories(dir)
        val upAnim = commonClimbAnim(LadderTag.Up, LadderTag.DungeonUp)
        val downAnim = commonClimbAnim(LadderTag.Down, LadderTag.DungeonDown)
        val toml = buildString {
            appendLine("# Generated by the travel coverage report (::travelreport). Each ladder below")
            appendLine("# has a matching ladder one level away, or 6400 tiles away for a dungeon, at")
            appendLine("# every placement, so the shared ladder scripts can serve it.")
            for (suggestion in result.suggestions.sortedBy { it.locId }) {
                val symbol = internalName(suggestion.locId)
                appendLine()
                appendLine("# ${type(suggestion.locId)?.name} - ${suggestion.placements} placements")
                appendLine("[[object]]")
                appendLine("id = \"$symbol\"")
                appendLine("inherit = \"$symbol\"")
                appendLine("contentGroup = \"${suggestion.tag.content}\"")
                val hasAnim = type(suggestion.locId)?.hasParam(params.climb_anim) == true
                val climbsDown = suggestion.tag == LadderTag.Down || suggestion.tag == LadderTag.DungeonDown
                val fallbackAnim = if (climbsDown) downAnim else upAnim
                if (!hasAnim && fallbackAnim != null) {
                    appendLine()
                    appendLine("[object.params]")
                    appendLine("\"param.climb_anim\" = \"$fallbackAnim\"")
                }
            }
        }
        Files.writeString(dir.resolve("ladder-tags.toml"), toml)

        val skipped = buildString {
            appendLine("# Ladders the auto-tagger left alone")
            appendLine()
            appendLine("| Loc | Symbol | Reason |")
            appendLine("|---|---|---|")
            for (skip in result.skipped.sortedBy { it.reason }) {
                appendLine("| ${skip.name} (${skip.locId}) | `${internalName(skip.locId)}` | ${skip.reason} |")
            }
        }
        Files.writeString(dir.resolve("ladder-skipped.md"), skipped)
    }

    private fun commonClimbAnim(vararg tags: LadderTag): String? {
        val groups = tags.map { it.content.asRSCM(RSCMType.CONTENT) }.toSet()
        val anims =
            ServerCacheManager.getObjects()
                .values
                .filter { it.contentGroup in groups }
                .mapNotNull { it.paramOrNull<SequenceServerType>(params.climb_anim)?.id }
        val id = anims.groupingBy { it }.eachCount().maxByOrNull { it.value }?.key ?: return null
        return runCatching { RSCM.getReverseMapping(RSCMType.SEQ, id) }.getOrNull()
    }
}
