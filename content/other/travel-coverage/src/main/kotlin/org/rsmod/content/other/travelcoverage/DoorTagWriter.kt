package org.rsmod.content.other.travelcoverage

import java.nio.file.Files
import java.nio.file.Path

/**
 * Writes `door-tags.toml`, a pack config that tags each paired door's closed and open models
 * and points them at each other through `next_loc_stage`, the two-state machine the shared door
 * scripts expect.
 */
object DoorTagWriter {
    fun write(suggestions: List<DoorSuggestion>, dir: Path) {
        Files.createDirectories(dir)
        val toml = buildString {
            appendLine("# Generated by the travel coverage report (gradlew travelReport). Each closed door")
            appendLine("# below is paired with the open model named after it, so the shared door")
            appendLine("# and gate scripts can swap between the two.")
            for (door in suggestions.sortedBy { it.closed }) {
                appendLine()
                append(entry(door.closed, door.kind.closed, door.opened))
                appendLine()
                append(entry(door.opened, door.kind.opened, door.closed))
            }
        }
        Files.writeString(dir.resolve("door-tags.toml"), toml)
    }

    private fun entry(symbol: String, content: String, nextStage: String): String =
        buildString {
            appendLine("[[object]]")
            appendLine("id = \"$symbol\"")
            appendLine("inherit = \"$symbol\"")
            appendLine("contentGroup = \"$content\"")
            appendLine()
            appendLine("[object.params]")
            appendLine("\"param.next_loc_stage\" = \"$nextStage\"")
        }
}
