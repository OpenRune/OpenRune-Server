    private fun DBTableBuilder.floor(
        row: String,
        floor: Int,
        forward: List<Pair<CoordGrid, CoordGrid>>,
        backward: List<Pair<CoordGrid, CoordGrid>>,
    ) {
        row(row) {
            column(FLOOR, floor)
            column(FORWARD, forward.flatMap { listOf(it.first.packed, it.second.packed) })
            column(BACKWARD, backward.flatMap { listOf(it.first.packed, it.second.packed) })
        }
    }
